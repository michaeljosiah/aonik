// Canonical generated headshots are copied byte-for-byte into the application's public assets.
import {readFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const kit=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const root=path.resolve(kit,'../..');
const catalog=JSON.parse(await readFile(path.join(kit,'assets/agent-portraits/catalog.json'),'utf8'));
const normalize=value=>value.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');
const aliases=new Map();
for(const entry of catalog.entries){
  if(!/^[a-z0-9-]+\.png$/.test(entry.file) || entry.file!==entry.id+'.png')throw Error('Invalid portrait path: '+entry.id);
  for(const alias of entry.aliases){const key=normalize(alias);if(aliases.has(key))throw Error('Duplicate agent alias: '+alias);aliases.set(key,entry.id);}
}
const registered=[];
for(const module of ['Aonik.Finance','Aonik.Platform','Aonik.Commerce','Aonik.PersonalFinance']){
  const folder=path.join(root,'src',module,'Agents');
  for(const file of await readdir(folder))if(file.endsWith('Registration.cs')){
    const name=(await readFile(path.join(folder,file),'utf8')).match(/public string Name => "([^"]+)"/);
    if(name){registered.push(name[1]);if(!aliases.has(normalize(name[1])))throw Error('No portrait mapping for registered agent: '+name[1]);}
  }
}
if(!aliases.has('master-orchestrator'))throw Error('Orchestrator portrait is missing');
const template=await readFile(path.join(kit,'screens/agents-page.jsx'),'utf8');
for(const [,id] of template.slice(template.indexOf('const AGENT_LIST'),template.indexOf('const STATE_DOT')).matchAll(/id: '([^']+)'/g))
  if(!aliases.has(normalize(id)))throw Error('No portrait mapping for starter-kit agent: '+id);
const checks=[];const outputs=[];
for(const entry of catalog.entries){
  const bytes=await readFile(path.join(kit,'assets/agent-portraits',entry.file));
  if(bytes.subarray(0,8).toString('hex')!=='89504e470d0a1a0a')throw Error('Expected PNG: '+entry.file);
  const width=bytes.readUInt32BE(16),height=bytes.readUInt32BE(20);
  if(width!==height || width<512)throw Error('Portrait must be square and at least 512px: '+entry.file);
  checks.push({id:entry.id,width,height,sha256:createHash('sha256').update(bytes).digest('hex')});
  outputs.push([path.join(root,'src/Aonik.AdminUi/public/images/agents','cgi-'+entry.file),bytes]);
}
const json=JSON.stringify(catalog.entries,null,2);
const normalizer="value.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'')";
outputs.push([path.join(kit,'assets/agent-portraits.js'),`// Generated by scripts/build-agent-portraits.mjs.\n(()=>{\nconst entries=${json};\nconst base=new URL('agent-portraits/',document.currentScript.src);\nconst normalize=value=>${normalizer};\nconst resolve=name=>{const key=normalize(name||'');const entry=entries.find(item=>item.aliases.some(alias=>normalize(alias)===key));return entry?new URL(entry.file,base).href:undefined;};\nglobalThis.AonikAgentPortraits=Object.freeze({entries,resolve});\n})();\n`]);
outputs.push([path.join(root,'src/Aonik.AdminUi/src/lib/agentPortraits.generated.ts'),`// Generated from the canonical starter-kit portrait catalog. Do not edit by hand.\nexport const AGENT_PORTRAITS = ${json} as const;\nconst normalize=(value: string)=>${normalizer};\nexport function resolveAgentPortrait(name: string): string | undefined {\n  const key=normalize(name);\n  const entry=AGENT_PORTRAITS.find(item=>item.aliases.some(alias=>normalize(alias)===key));\n  return entry?\`/images/agents/cgi-\${entry.file}\`:undefined;\n}\n`]);
outputs.push([path.join(kit,'assets/agent-portraits/assets.json'),JSON.stringify({generator:catalog.generator,generatedOn:catalog.generatedOn,registeredAgents:registered,portraits:checks},null,2)+'\n']);
for(const [file,content] of outputs){
  if(process.argv.includes('--check')){
    let current;try{current=await readFile(file);}catch{throw Error('Missing generated portrait asset: '+file);}
    if(!current.equals(Buffer.isBuffer(content)?content:Buffer.from(content)))throw Error('Portrait assets drifted: '+file);
  }else{await mkdir(path.dirname(file),{recursive:true});await writeFile(file,content);}
}
console.log(`${process.argv.includes('--check')?'Verified':'Generated'} ${checks.length} CGI portraits, browser/React mappings, and coverage for ${registered.length} registered domain agents plus the orchestrator and starter-kit personas.`);
