// Export tiny, synthetic reader fixtures; never export a creator's world.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import '../lib/verify.dart';
import 'verification_test.dart' as fixtures;

Future<void> main(List<String> args) async {
  final output = Directory(args.single).absolute;
  await output.create(recursive: true);
  String? baseFingerprint;
  for (final kind in ['world', 'listening', 'guide', 'music', 'story', 'comic', 'part']) {
    final entries = fixtures.example(kind == 'part' ? 'listening' : kind);
    final manifest = jsonDecode(utf8.decode(entries['world.json']!)) as Map<String, dynamic>;
    // Every review needs a real, declared cover, also for otherwise book-only packages.
    final cover = base64Decode('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j1ioAAAAASUVORK5CYII=');
    final productionList = manifest['productions'] as List;
    final coverId = manifest['keyArt'] as String? ?? (productionList.isNotEmpty ? productionList.first['picture'] as String? : null) ?? 'marketing-cover';
    final oldCover = (manifest['assets'] as Map)[coverId] as Map?;
    if (oldCover != null) entries.remove(oldCover['path']);
    (manifest['assets'] as Map)[coverId] = {'path':'marketing-cover.png','mediaType':'image/png','byteLength':cover.length,'sha256':sha256.convert(cover).toString()};
    if (manifest['alone'] == true || kind == 'part') { productionList.first['picture'] = coverId; } else { manifest['keyArt'] = coverId; }
    entries['marketing-cover.png'] = cover;
    if (kind == 'part') {
      manifest['schemaVersion'] = 4;
      manifest['edition'] = '2026-11-04';
      manifest['part'] = {'follows':'2026-11-03','fingerprint':baseFingerprint,'number':1};
      final asset = (manifest['assets'] as Map)['listening'] as Map;
      final document = jsonDecode(utf8.decode(entries[asset['path']]!)) as Map<String,dynamic>;
      for (final chapter in document['chapters'] as List) {
        chapter['id'] = 'next-${chapter['id']}';
        chapter['order'] += 20;
      }
      final bytes = utf8.encode(jsonEncode(document));entries[asset['path']] = bytes;
      asset['byteLength'] = bytes.length;asset['sha256'] = sha256.convert(bytes).toString();
    }
    entries['world.json'] = utf8.encode(jsonEncode(manifest));
    final scratch = await Directory.systemTemp.createTemp('aonik-golden-');
    try {
      final archive = await fixtures.zip(scratch, entries);
      final hash = (await sha256.bind(archive.openRead()).first).toString();
      final report = await verifyPackage(archive.path, hash, await archive.length(),maxAssets:1024,maxAssetBytes:268435456,maxDocumentBytes:4194304,scratchRoot:scratch.path);
      if (kind == 'listening') baseFingerprint = report['fingerprint'] as String;
      await archive.copy('${output.path}/$kind.zip');
      await File('${output.path}/$kind.json').writeAsString('${const JsonEncoder.withIndent('  ').convert(report)}\n');
    } finally { await scratch.delete(recursive: true); }
  }
  await File('${output.path}/provenance.json').writeAsString('${jsonEncode({'readerCommit':readerCommit,'source':'synthetic fixtures from the pinned pure Dart reader; regenerated by export_fixtures.dart'})}\n');
}
